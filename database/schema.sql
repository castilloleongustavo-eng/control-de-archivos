CREATE DATABASE IF NOT EXISTS admosa_file_manager CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE admosa_file_manager;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS files (
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 original_name VARCHAR(180) NOT NULL,
 stored_name CHAR(64) CHARACTER SET ascii NOT NULL UNIQUE,
 mime_type VARCHAR(100) NOT NULL,
 extension VARCHAR(5) NOT NULL,
 file_size BIGINT UNSIGNED NOT NULL,
 storage_path VARCHAR(100) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX files_owner_created (user_id, created_at),
 CONSTRAINT files_owner_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS auth_attempts (
 bucket CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_start BIGINT UNSIGNED NOT NULL,
 INDEX auth_window (window_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
